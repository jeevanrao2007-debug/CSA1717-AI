s = "Python Programming"
 
print("Original string  :", s)
print("s[0:6]           :", s[0:6])
print("s[7:]            :", s[7:])
print("s[:6]            :", s[:6])
print("s[-11:]          :", s[-11:])
print("s[::2]           :", s[::2])
print("s[::-1] (reverse):", s[::-1])
print("s[:]             :", s[:])
